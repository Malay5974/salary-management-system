import { PGlite } from '@electric-sql/pglite';
import { neon } from '@neondatabase/serverless';
import { mkdirSync } from 'node:fs';

export type Row = Record<string, unknown>;
export interface Database {
  query<T extends Row = Row>(sql: string, params?: unknown[]): Promise<T[]>;
}

declare global {
  // Keep one local database instance across Next.js hot reloads.
  var salaryDb: Promise<PGlite> | undefined;
}

export function getDatabase(): Database {
  const url = process.env.DATABASE_URL;
  if (url) {
    const sql = neon(url);
    return { query: async <T extends Row>(text: string, params: unknown[] = []) =>
      await sql.query(text, params) as T[] };
  }
  if (process.env.VERCEL) throw new Error('DATABASE_URL is required on Vercel');
  mkdirSync('.data', { recursive: true });
  globalThis.salaryDb ??= PGlite.create('.data/salary.db');
  return { query: async <T extends Row>(text: string, params: unknown[] = []) => {
    const db = await globalThis.salaryDb!;
    return (await db.query<T>(text, params)).rows;
  } };
}

const schema = `
CREATE SEQUENCE IF NOT EXISTS employees_id_seq START 1000001;
CREATE TABLE IF NOT EXISTS employees (
  id BIGINT PRIMARY KEY,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  department TEXT NOT NULL,
  country TEXT NOT NULL,
  currency CHAR(3) NOT NULL,
  start_date DATE NOT NULL,
  salary_minor BIGINT NOT NULL CHECK (salary_minor >= 0),
  salary_effective_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE employees ALTER COLUMN id SET DEFAULT nextval('employees_id_seq');
CREATE INDEX IF NOT EXISTS employees_name_idx ON employees (last_name, first_name, id);
CREATE INDEX IF NOT EXISTS employees_country_department_idx ON employees (country, department);
CREATE TABLE IF NOT EXISTS salary_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES employees(id),
  old_salary_minor BIGINT NOT NULL CHECK (old_salary_minor >= 0),
  new_salary_minor BIGINT NOT NULL CHECK (new_salary_minor >= 0),
  effective_date DATE NOT NULL,
  reason TEXT NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS salary_changes_employee_idx ON salary_changes (employee_id, changed_at DESC);
`;

let ready: Promise<void> | undefined;
export function ensureSchema(db = getDatabase()): Promise<void> {
  ready ??= (async () => {
    for (const statement of schema.split(';').map(s => s.trim()).filter(Boolean)) await db.query(statement);
  })().catch(error => { ready = undefined; throw error; });
  return ready;
}
