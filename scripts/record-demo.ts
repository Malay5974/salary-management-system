import { chromium } from 'playwright';
import { mkdirSync, readdirSync, renameSync, rmSync, readFileSync } from 'node:fs';

const output = 'docs/demo';
const baseUrl = process.env.DEMO_BASE_URL ?? 'http://127.0.0.1:3000';
const credentials = readFileSync('.data/demo-login.txt', 'utf8');
const email = credentials.match(/^Email: (.+)$/m)?.[1];
const password = credentials.match(/^Password: (.+)$/m)?.[1];
if (!email || !password) throw new Error('Run npm run auth:setup before recording the demo');
mkdirSync(output, { recursive: true });
for (const file of readdirSync(output).filter(name => name.endsWith('.webm'))) rmSync(`${output}/${file}`, { force: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, recordVideo: { dir: output, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const pause = (ms: number) => page.waitForTimeout(ms);

await page.goto(baseUrl, { waitUntil: 'networkidle' });
await page.getByRole('textbox', { name: 'Email' }).fill(email);
await page.getByLabel('Password').fill(password);
await pause(600);
await page.getByRole('button', { name: 'Sign in' }).click();
await page.getByText('10,000', { exact: true }).waitFor();
await pause(1800);
await page.getByRole('button', { name: 'Employees' }).click();
await page.getByText('10,000 employees').waitFor();
await pause(1400);
await page.getByRole('textbox', { name: 'Search employees' }).fill('employee1');
await page.getByText('1,112 employees').waitFor();
await pause(1200);
await page.locator('tbody tr').first().click();
await page.getByText('CURRENT ANNUAL SALARY').waitFor();
await pause(1400);
await page.getByRole('button', { name: 'Change salary' }).click();
await page.getByRole('textbox', { name: 'Reason' }).fill('Annual review');
const salary = page.getByRole('spinbutton', { name: /New annual salary/ });
await salary.fill(String(Number(await salary.inputValue()) + 1000));
await pause(900);
await page.getByRole('button', { name: 'Save salary change' }).click();
await page.locator('.history-item').first().getByText('Annual review').waitFor();
await pause(1600);
await page.getByRole('button', { name: 'Close' }).click();
await page.getByRole('button', { name: 'Import spreadsheet' }).click();
await page.locator('input[type=file]').setInputFiles('public/employee-import-template.csv');
await page.getByRole('button', { name: 'Preview import' }).click();
await page.getByText('Review changes').waitFor();
await pause(1400);
await page.getByRole('button', { name: 'Close' }).click();
await page.getByRole('button', { name: 'Overview' }).click();
await pause(1800);
await page.getByRole('button', { name: 'Sign out' }).click();
await page.getByRole('button', { name: 'Sign in' }).waitFor();
await pause(900);
await context.close();
await browser.close();
const files = readdirSync(output).filter(name => name.endsWith('.webm'));
if (files.length !== 1) throw new Error(`Expected one video, found ${files.length}`);
renameSync(`${output}/${files[0]}`, `${output}/salary-management-demo.webm`);
console.log(`${output}/salary-management-demo.webm`);
